"""Run benchmark tasks through Baton: sandbox per task, one `jev run`, then grade.

Manual trigger only (`jev capbench run`): there is deliberately no scheduled or
recurring run - the ~$3-7/night model spend needs the maintainer's explicit
go-ahead (design §5). Each task gets a throwaway sandbox git repo copied from
its fixture, a generated `jev.toml` with the fixed budget cap and `basic`
quality level, and the pinned worker profile. Grading runs on the merged
result branch (`jev/<run>/result`), exactly where the integration gate runs.
"""

from __future__ import annotations

import asyncio
import json
import os
import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from jev_agent.app.context import open_context
from jev_agent.app.runs import start_run
from jev_agent.capbench.grading import run_grade_script
from jev_agent.capbench.models import (
    DEFAULT_PER_RUN_USD,
    DEFAULT_PROFILE,
    DEFAULT_QUALITY_LEVEL,
    GradeReport,
    SuiteResult,
    TaskResult,
    TaskSpec,
    load_task,
    load_tasks,
    task_result_from_grade,
)
from jev_agent.core.models import RunState
from jev_agent.core.workspace import (
    GIT_QUICK_TIMEOUT_S,
    GIT_SLOW_TIMEOUT_S,
    result_branch,
    run_git,
)

# The sandbox `jev.toml` every benchmark run gets: fixed budget cap, `basic`
# quality level (fewer checks, fewer model calls), no plan approval gate (the
# benchmark is the approval), and the worker profile pinned to the API worker
# so the run uses the maintainer's cheap benchmark model.
#
# Maintainer: pin the cheap benchmark model before the first real run, e.g.
#   [workers.api]
#   default_model = "openrouter/<your-cheap-tier-model>"
# or per-role `[roles.coder] models = [...]`. The key itself comes from the
# environment (`OPENROUTER_API_KEY`), never from this file.
BENCHMARK_TOML_TEMPLATE = """\
# Generated by `jev capbench run` - fixed benchmark harness config, do not edit by hand.
[budget]
per_run_usd = {per_run_usd}
per_task_usd = {per_task_usd}

[quality]
level = "basic"

[approval]
require_plan_approval = false

[workers.api]
enabled = true
# Pin the cheap benchmark model here (see runner.py BENCHMARK_TOML_TEMPLATE).

[roles.planner]
workers = ["api"]
[roles.validator]
workers = ["api"]
[roles.coder]
workers = ["api"]
[roles.reviewer]
workers = ["api"]
[roles.code_reviewer]
workers = ["api"]
[roles.learner]
workers = ["api"]
"""


@dataclass
class BenchmarkConfig:
    """Knobs for a benchmark suite run (manual trigger only)."""

    profile: str = DEFAULT_PROFILE
    per_run_usd: float = DEFAULT_PER_RUN_USD
    quality_level: str = DEFAULT_QUALITY_LEVEL
    workdir: Path | None = None  # None: a temp dir; kept sandboxes print their path
    keep_sandbox: bool = True
    timeout_min: float | None = None  # None: no timeout; a run may take 30-90 min


def benchmark_toml(per_run_usd: float) -> str:
    """The sandbox `jev.toml`: the budget cap, with per-task capped below it."""
    return BENCHMARK_TOML_TEMPLATE.format(
        per_run_usd=per_run_usd, per_task_usd=min(1.5, per_run_usd)
    )


def _git(sandbox: Path, *args: str, slow: bool = False) -> subprocess.CompletedProcess[str]:
    """`git …` in the sandbox with a timeout; a nonzero exit raises, as with `check=True`."""
    proc = run_git(args, sandbox, GIT_SLOW_TIMEOUT_S if slow else GIT_QUICK_TIMEOUT_S)
    if proc.returncode != 0:
        raise subprocess.CalledProcessError(proc.returncode, proc.args, proc.stdout, proc.stderr)
    return proc


def prepare_sandbox(task: TaskSpec, parent: Path, config: BenchmarkConfig) -> tuple[Path, str]:
    """Copy the task fixture into a fresh git repo; return (sandbox, base commit sha).

    The agent builds in the sandbox, never in the fixture the grader knows, so
    tasks cannot rot when Baton refactors and cannot depend on Baton's
    internals (design §2).
    """
    sandbox = parent / task.id
    if sandbox.exists():
        shutil.rmtree(sandbox)
    shutil.copytree(task.fixture_dir, sandbox)
    _git(sandbox, "init", "-q", "-b", "main")
    _git(sandbox, "add", "-A")
    _git(
        sandbox,
        "-c",
        "user.name=capbench",
        "-c",
        "user.email=capbench@example.com",
        "commit",
        "-q",
        "-m",
        f"benchmark fixture: {task.id}",
        slow=True,  # commit can run repo hooks
    )
    (sandbox / "jev.toml").write_text(benchmark_toml(config.per_run_usd), encoding="utf-8")
    base_sha = _git(sandbox, "rev-parse", "HEAD").stdout.strip()
    return sandbox, base_sha


def _run_json_for(run_id: str, store: Any, ship_score: int | None) -> dict[str, Any]:
    run = store.get_run(run_id)
    return {
        "run_id": run_id,
        "ship_score": ship_score,
        "cost_usd": run.spend_usd,
        "state": run.state.value if isinstance(run.state, RunState) else str(run.state),
    }


def _integration_ship_score(store: Any, run_id: str) -> int | None:
    """The latest integration-scope gate's ship score, None when no gate ran."""
    reports = [r for r in store.list_quality_reports(run_id) if r.result.scope == "integration"]
    if not reports:
        return None
    score = reports[-1].result.score
    return score.total if score is not None else None


def _result_diff(sandbox: Path, base_sha: str, run_id: str) -> tuple[Path, str]:
    """The unified diff base..result-branch; empty when the run produced no branch."""
    branch = result_branch(run_id)
    proc = subprocess.run(
        ["git", "rev-parse", "--verify", "--quiet", branch],
        cwd=sandbox,
        capture_output=True,
        text=True,
    )
    diff_text = ""
    if proc.returncode == 0:
        diff_text = _git(sandbox, "diff", f"{base_sha}..{branch}").stdout
    diff_path = sandbox / ".jev" / "capbench.diff"
    diff_path.parent.mkdir(parents=True, exist_ok=True)
    diff_path.write_text(diff_text, encoding="utf-8")
    return diff_path, diff_text


def _checkout_result(sandbox: Path, run_id: str, dest: Path) -> Path:
    """A clean checkout of the result branch (the agent's code, no `.jev/` state).

    `.jev/` only ever holds *untracked* run artifacts (capbench-run.json,
    capbench.diff), so nothing under it is committed to the result branch and
    checking out the tracked files (`<branch> -- .`) cannot leak sandbox state.
    """
    branch = result_branch(run_id)
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    _git(sandbox, "--work-tree", str(dest), "checkout", branch, "--", ".", slow=True)
    return dest


def run_task(
    task_id: str,
    config: BenchmarkConfig,
    tasks_dir: Path | None = None,
) -> TaskResult:
    """Run one benchmark task through Baton and grade it; the manual trigger.

    Returns a TaskResult whose `note` explains a run that never completed
    (no result branch, harness error) instead of fabricating dimensions.
    Unless `keep_sandbox` is set, the sandbox is removed on every exit path,
    not just the success path.
    """
    spec = load_task(task_id, tasks_dir)
    started = datetime.now(UTC)
    parent = config.workdir or Path(tempfile.mkdtemp(prefix="capbench-"))
    parent.mkdir(parents=True, exist_ok=True)
    sandbox, base_sha = prepare_sandbox(spec, parent, config)
    try:
        return _run_task_in_sandbox(spec, config, started, parent, sandbox, base_sha)
    finally:
        # The old code only removed the sandbox on the success path, so a
        # timed-out, failed or harness-error run leaked one sandbox per task.
        if not config.keep_sandbox:
            shutil.rmtree(sandbox, ignore_errors=True)


def _run_task_in_sandbox(
    spec: TaskSpec,
    config: BenchmarkConfig,
    started: datetime,
    parent: Path,
    sandbox: Path,
    base_sha: str,
) -> TaskResult:
    """One task's run-and-grade inside an already-prepared sandbox."""

    async def _run() -> Any:
        with open_context(sandbox) as ctx:
            return await start_run(ctx, spec.brief, quality=config.quality_level, no_learning=True)

    try:
        if config.timeout_min is not None:
            record = asyncio.run(asyncio.wait_for(_run(), timeout=config.timeout_min * 60))
        else:
            record = asyncio.run(_run())
    except TimeoutError:
        return _failed_task(
            spec, config, started, note=f"run timed out after {config.timeout_min} min"
        )
    except Exception as exc:
        return _failed_task(spec, config, started, note=f"run failed to start: {exc}")

    duration_min = (datetime.now(UTC) - started).total_seconds() / 60
    run_date = started.date().isoformat()

    with open_context(sandbox) as ctx:
        store = ctx.store
        run = store.get_run(record.id)
        ship_score = _integration_ship_score(store, record.id)
        run_json = _run_json_for(record.id, store, ship_score)
    run_json_path = sandbox / ".jev" / "capbench-run.json"
    run_json_path.write_text(json.dumps(run_json, indent=2), encoding="utf-8")
    diff_path, _ = _result_diff(sandbox, base_sha, record.id)

    if run.state is not RunState.DONE:
        return _failed_task(
            spec,
            config,
            started,
            run_id=record.id,
            cost_usd=run.spend_usd,
            duration_min=duration_min,
            run_date=run_date,
            ship_score=ship_score,
            note=f"run ended {run.state.value}: {run.reason or 'no reason recorded'}",
        )

    result_dir = _checkout_result(sandbox, record.id, parent / f"{spec.id}-result")
    try:
        grade = run_grade_script(spec.grade_py, result_dir, run_json_path, diff_path)
    except RuntimeError as exc:
        return _failed_task(
            spec,
            config,
            started,
            run_id=record.id,
            cost_usd=run.spend_usd,
            duration_min=duration_min,
            run_date=run_date,
            ship_score=ship_score,
            note=f"grader harness error: {exc}",
        )
    return task_result_from_grade(
        spec,
        grade,
        run_id=record.id,
        cost_usd=run.spend_usd,
        duration_min=duration_min,
        profile=config.profile,
        run_date=run_date,
    )


def _failed_task(
    spec: TaskSpec,
    config: BenchmarkConfig,
    started: datetime,
    *,
    run_id: str | None = None,
    cost_usd: float = 0.0,
    duration_min: float = 0.0,
    run_date: str = "",
    ship_score: int | None = None,
    note: str,
) -> TaskResult:
    """A TaskResult for a task that never produced gradable code - zeros, not guesses."""
    return TaskResult(
        task_id=spec.id,
        title=spec.title,
        run_id=run_id,
        passed=False,
        correctness=0.0,
        ship_score=ship_score,
        cost_usd=cost_usd,
        duration_min=duration_min,
        profile=config.profile,
        run_date=run_date or started.date().isoformat(),
        grade=GradeReport(
            task_id=spec.id,
            passed=False,
            tests_passed=0,
            tests_total=0,
            diff_added=0,
            diff_files=0,
            diff_within_band=False,
            ship_score=ship_score,
            reasons=[note],
        ),
        note=note,
    )


def run_suite(
    task_ids: list[str] | None,
    config: BenchmarkConfig,
    tasks_dir: Path | None = None,
    out_path: Path | None = None,
) -> SuiteResult:
    """Run the suite (one `jev run` per task) and collect the results.

    `task_ids=None` runs every task. Each task runs once (Phase 1: n=1, and
    the scoreboard says so). Duplicate ids are dropped (order preserved): each
    task spends model money, so `--task t1 --task t1` must not bill twice.

    One task's failure must never discard the others (a suite is hours of
    model spend): the per-task body is isolated, and a failure becomes a
    `_failed_task` with an explanatory `note` - zeros, not guesses. When
    `out_path` is given the suite JSON is rewritten after every task, so even
    a crash mid-suite keeps the completed results.
    """
    specs = load_tasks(tasks_dir)
    ids = task_ids if task_ids is not None else [spec.id for spec in specs]
    ids = list(dict.fromkeys(ids))  # dedupe, preserving order
    specs_by_id = {spec.id: spec for spec in specs}
    unknown = [task_id for task_id in ids if task_id not in specs_by_id]
    if unknown:
        raise ValueError(f"unknown benchmark task(s): {', '.join(unknown)}")

    def _partial(results: list[TaskResult]) -> SuiteResult:
        return SuiteResult(
            evaluated=True,
            profile=config.profile,
            commit=_repo_commit(),
            repeats_per_task=1,
            per_run_usd=config.per_run_usd,
            tasks=list(results),
            note="Phase 1: each task ran once (n=1); single-run scores, no repeats.",
        )

    results: list[TaskResult] = []
    for task_id in ids:
        try:
            results.append(run_task(task_id, config, tasks_dir))
        except Exception as exc:  # a suite must survive one bad task
            results.append(
                _failed_task(
                    specs_by_id[task_id],
                    config,
                    datetime.now(UTC),
                    note=f"harness error: {exc}",
                )
            )
        if out_path is not None:
            write_suite_json(_partial(results), out_path)
    return _partial(results)


def _repo_commit() -> str | None:
    """The baton commit the suite ran against (this file's repo), if available."""
    try:
        proc = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=Path(__file__).resolve().parents[3],
            capture_output=True,
            text=True,
            check=True,
        )
        return proc.stdout.strip()
    except (subprocess.CalledProcessError, OSError):
        return None


def write_suite_json(suite: SuiteResult, path: Path) -> Path:
    """Write a suite result (evaluated or template) as JSON, atomically.

    Temp-file + rename: a crash mid-write never leaves a truncated suite JSON
    (matters most for the incremental writes `run_suite` does after each task).
    """
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(suite.model_dump_json(indent=2), encoding="utf-8")
    os.replace(tmp, path)
    return path


